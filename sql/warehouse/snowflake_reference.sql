-- Snowflake SQL reference examples.
-- Documentation only. Not executed locally.
-- Execution in Snowflake may incur charges.
-- Appropriate privileges and edition are required.

CREATE WAREHOUSE IF NOT EXISTS HEALTHCARE_ANALYTICS_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS HEALTHCARE_DB;

CREATE SCHEMA IF NOT EXISTS HEALTHCARE_DB.ANALYTICS;

CREATE TABLE IF NOT EXISTS HEALTHCARE_DB.ANALYTICS.PATIENTS (
    PATIENT_ID VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL,
    AGE INTEGER,
    PRIOR_VISITS INTEGER,
    NO_SHOW INTEGER
);

CREATE TRANSIENT TABLE IF NOT EXISTS
    HEALTHCARE_DB.ANALYTICS.PATIENT_STAGING (
        PATIENT_ID VARCHAR,
        REGION VARCHAR
    );

CREATE TEMPORARY TABLE
    HEALTHCARE_DB.ANALYTICS.SESSION_PATIENTS (
        PATIENT_ID VARCHAR
    );

CREATE OR REPLACE VIEW
    HEALTHCARE_DB.ANALYTICS.REGIONAL_METRICS AS
SELECT
    REGION,
    COUNT(*) AS TOTAL_PATIENTS,
    AVG(AGE) AS AVERAGE_AGE
FROM HEALTHCARE_DB.ANALYTICS.PATIENTS
GROUP BY REGION;

-- Materialized view example.
-- Edition and feature restrictions apply.

CREATE MATERIALIZED VIEW IF NOT EXISTS
    HEALTHCARE_DB.ANALYTICS.PATIENT_PROJECTION AS
SELECT PATIENT_ID, REGION, AGE
FROM HEALTHCARE_DB.ANALYTICS.PATIENTS;

-- Scale-up.

ALTER WAREHOUSE HEALTHCARE_ANALYTICS_WH
    SET WAREHOUSE_SIZE = 'SMALL';

-- Scale-out.
-- Requires compatible Snowflake edition.

ALTER WAREHOUSE HEALTHCARE_ANALYTICS_WH
    SET MIN_CLUSTER_COUNT = 1
        MAX_CLUSTER_COUNT = 2
        SCALING_POLICY = 'STANDARD';

-- Inspect warehouses and objects.

SHOW WAREHOUSES;

SHOW DATABASES;

SHOW SCHEMAS IN DATABASE HEALTHCARE_DB;

SHOW TABLES IN SCHEMA HEALTHCARE_DB.ANALYTICS;

-- Query history.

SELECT *
FROM TABLE(
    HEALTHCARE_DB.INFORMATION_SCHEMA.QUERY_HISTORY(
        RESULT_LIMIT => 10
    )
);

-- Query plan inspection.

EXPLAIN USING TEXT
SELECT REGION, COUNT(*)
FROM HEALTHCARE_DB.ANALYTICS.PATIENTS
GROUP BY REGION;

-- Clustering example.
-- Evaluate workload and maintenance cost before use.

ALTER TABLE HEALTHCARE_DB.ANALYTICS.PATIENTS
    CLUSTER BY (REGION);

-- Disable persisted result reuse for a session benchmark.

ALTER SESSION SET USE_CACHED_RESULT = FALSE;

-- Restore normal result reuse.

ALTER SESSION SET USE_CACHED_RESULT = TRUE;

-- Role-Based Access Control.

CREATE ROLE IF NOT EXISTS HEALTHCARE_ANALYST;

GRANT USAGE
    ON WAREHOUSE HEALTHCARE_ANALYTICS_WH
    TO ROLE HEALTHCARE_ANALYST;

GRANT USAGE
    ON DATABASE HEALTHCARE_DB
    TO ROLE HEALTHCARE_ANALYST;

GRANT USAGE
    ON SCHEMA HEALTHCARE_DB.ANALYTICS
    TO ROLE HEALTHCARE_ANALYST;

GRANT SELECT
    ON VIEW HEALTHCARE_DB.ANALYTICS.REGIONAL_METRICS
    TO ROLE HEALTHCARE_ANALYST;

SHOW GRANTS TO ROLE HEALTHCARE_ANALYST;

-- Resource monitoring.
-- Requires appropriate administrative privileges.

CREATE RESOURCE MONITOR IF NOT EXISTS HEALTHCARE_MONITOR
    WITH CREDIT_QUOTA = 10
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 80 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE HEALTHCARE_ANALYTICS_WH
    SET RESOURCE_MONITOR = HEALTHCARE_MONITOR;

-- Suspend compute resources.

ALTER WAREHOUSE HEALTHCARE_ANALYTICS_WH SUSPEND;
