-- Dynamic table refresh managed by Snowflake.
-- Target lag is a freshness objective, not a fixed schedule.

CREATE DYNAMIC TABLE IF NOT EXISTS
    REGIONAL_PATIENT_ANALYTICS
    TARGET_LAG = '5 minutes'
    WAREHOUSE = HEALTHCARE_COMPUTE
    REFRESH_MODE = INCREMENTAL
    INITIALIZE = ON_CREATE
AS
SELECT
    REGION,
    COUNT(*) AS TOTAL_PATIENTS,
    SUM(PRIOR_VISITS) AS TOTAL_VISITS,
    SUM(NO_SHOW) AS MISSED_APPOINTMENTS,
    AVG(AGE) AS AVERAGE_AGE,
    100.0 * SUM(NO_SHOW)
        / NULLIF(COUNT(*), 0)
        AS NO_SHOW_RATE_PCT
FROM PATIENT_TARGET
GROUP BY REGION;

