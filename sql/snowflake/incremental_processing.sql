CREATE WAREHOUSE IF NOT EXISTS HEALTHCARE_COMPUTE
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS HEALTHCARE_PLATFORM;

CREATE SCHEMA IF NOT EXISTS
    HEALTHCARE_PLATFORM.INCREMENTAL;

USE DATABASE HEALTHCARE_PLATFORM;

USE SCHEMA INCREMENTAL;

CREATE TABLE IF NOT EXISTS PATIENT_SOURCE (
    PATIENT_ID VARCHAR,
    REGION VARCHAR,
    AGE INTEGER,
    PRIOR_VISITS INTEGER,
    NO_SHOW INTEGER,
    UPDATED_AT TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PATIENT_TARGET
    LIKE PATIENT_SOURCE;

-- Standard stream tracks inserts, updates and deletes.

CREATE STREAM IF NOT EXISTS PATIENT_CHANGE_STREAM
    ON TABLE PATIENT_SOURCE
    APPEND_ONLY = FALSE
    SHOW_INITIAL_ROWS = TRUE;

-- Append-only stream tracks inserted rows.

CREATE STREAM IF NOT EXISTS PATIENT_INSERT_STREAM
    ON TABLE PATIENT_SOURCE
    APPEND_ONLY = TRUE;

SHOW STREAMS;

DESC STREAM PATIENT_CHANGE_STREAM;

SELECT
    PATIENT_ID,
    REGION,
    AGE,
    PRIOR_VISITS,
    NO_SHOW,
    METADATA$ACTION,
    METADATA$ISUPDATE,
    METADATA$ROW_ID
FROM PATIENT_CHANGE_STREAM;

SELECT SYSTEM$STREAM_HAS_DATA(
    'PATIENT_CHANGE_STREAM'
);

-- An UPDATE is represented by DELETE and INSERT records
-- in a standard Snowflake stream.
--
-- This MERGE assumes a unique source patient key and
-- no ambiguous multiple changes per target key.

MERGE INTO PATIENT_TARGET AS TARGET
USING (
    SELECT
        PATIENT_ID,
        REGION,
        AGE,
        PRIOR_VISITS,
        NO_SHOW,
        UPDATED_AT,
        METADATA$ACTION AS ACTION_TYPE,
        METADATA$ISUPDATE AS IS_UPDATE
    FROM PATIENT_CHANGE_STREAM
    WHERE NOT (
        METADATA$ACTION = 'DELETE'
        AND METADATA$ISUPDATE = TRUE
    )
) AS SOURCE
ON TARGET.PATIENT_ID = SOURCE.PATIENT_ID

WHEN MATCHED
    AND SOURCE.ACTION_TYPE = 'DELETE'
THEN DELETE

WHEN MATCHED
    AND SOURCE.ACTION_TYPE = 'INSERT'
THEN UPDATE SET
    REGION = SOURCE.REGION,
    AGE = SOURCE.AGE,
    PRIOR_VISITS = SOURCE.PRIOR_VISITS,
    NO_SHOW = SOURCE.NO_SHOW,
    UPDATED_AT = SOURCE.UPDATED_AT

WHEN NOT MATCHED
    AND SOURCE.ACTION_TYPE = 'INSERT'
THEN INSERT (
    PATIENT_ID,
    REGION,
    AGE,
    PRIOR_VISITS,
    NO_SHOW,
    UPDATED_AT
)
VALUES (
    SOURCE.PATIENT_ID,
    SOURCE.REGION,
    SOURCE.AGE,
    SOURCE.PRIOR_VISITS,
    SOURCE.NO_SHOW,
    SOURCE.UPDATED_AT
);

-- Scheduled warehouse-backed task.

CREATE TASK IF NOT EXISTS PATIENT_REFRESH_TASK
    WAREHOUSE = HEALTHCARE_COMPUTE
    SCHEDULE = '5 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA(
        'PATIENT_CHANGE_STREAM'
    )
AS
MERGE INTO PATIENT_TARGET AS TARGET
USING (
    SELECT
        PATIENT_ID,
        REGION,
        AGE,
        PRIOR_VISITS,
        NO_SHOW,
        UPDATED_AT,
        METADATA$ACTION AS ACTION_TYPE
    FROM PATIENT_CHANGE_STREAM
    WHERE NOT (
        METADATA$ACTION = 'DELETE'
        AND METADATA$ISUPDATE = TRUE
    )
) AS SOURCE
ON TARGET.PATIENT_ID = SOURCE.PATIENT_ID

WHEN MATCHED
    AND SOURCE.ACTION_TYPE = 'DELETE'
THEN DELETE

WHEN MATCHED
    AND SOURCE.ACTION_TYPE = 'INSERT'
THEN UPDATE SET
    REGION = SOURCE.REGION,
    AGE = SOURCE.AGE,
    PRIOR_VISITS = SOURCE.PRIOR_VISITS,
    NO_SHOW = SOURCE.NO_SHOW,
    UPDATED_AT = SOURCE.UPDATED_AT

WHEN NOT MATCHED
    AND SOURCE.ACTION_TYPE = 'INSERT'
THEN INSERT (
    PATIENT_ID,
    REGION,
    AGE,
    PRIOR_VISITS,
    NO_SHOW,
    UPDATED_AT
)
VALUES (
    SOURCE.PATIENT_ID,
    SOURCE.REGION,
    SOURCE.AGE,
    SOURCE.PRIOR_VISITS,
    SOURCE.NO_SHOW,
    SOURCE.UPDATED_AT
);

CREATE TABLE IF NOT EXISTS PATIENT_REFRESH_AUDIT (
    EXECUTED_AT TIMESTAMP_LTZ,
    TARGET_RECORDS INTEGER
);

-- Child task runs after the parent task.

CREATE TASK IF NOT EXISTS PATIENT_AUDIT_TASK
    WAREHOUSE = HEALTHCARE_COMPUTE
    AFTER PATIENT_REFRESH_TASK
AS
INSERT INTO PATIENT_REFRESH_AUDIT
SELECT
    CURRENT_TIMESTAMP(),
    COUNT(*)
FROM PATIENT_TARGET;

